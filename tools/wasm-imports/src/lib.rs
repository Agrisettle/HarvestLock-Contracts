//! Scan a compiled Soroban contract WASM for the host functions it imports.
//!
//! "Defended by absence" (threat-model entry 26) is a claim about the
//! *compiled artifact*: source review can show no `pub fn` for an upgrade or
//! deploy path, while a dependency, a macro expansion, or a stray extern
//! declaration can still link one in. This crate reads the import section of
//! the release WASM, resolves each short import name back to the host
//! function it calls using `soroban-env-common`'s `env.json`, and refuses a
//! configurable set of capabilities that this contract must never hold.
//!
//! The full import list is also committed as a snapshot. A new host
//! capability then shows up as a reviewable diff even when it is not on the
//! denylist yet.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use wasmparser::{Parser, Payload};

/// Every `(module, field)` import pair, sorted and deduplicated.
///
/// A set, not a map keyed by module: one host module supplies many imports
/// (`l:_`, `l:8`, `l:0`, …), and an earlier map-shaped version silently kept
/// only the last one per module.
pub type ImportList = BTreeSet<(String, String)>;

/// Embedded copy of `soroban-env-common`'s `env.json`.
///
/// The JSON lists each host module (`"ledger"`, `"context"`, …) with a
/// one-character export prefix, and each function with its one-character
/// suffix. Concatenating the two gives the short name the guest imports —
/// for example `ledger` + `6` is `l6`, which is
/// `update_current_contract_wasm`. `env.json` is the mapping the guest
/// actually compiles against, so it is the authoritative source here.
const ENV_JSON: &str = include_str!("../data/env.json");

/// A host capability the contract must never link.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DeniedFunction {
    /// Host function name as it appears in `env.json`.
    pub name: &'static str,
    /// Why linking it would widen the contract's authority.
    pub reason: &'static str,
}

/// Capabilities this contract deliberately does not have. Each one would let
/// a deployed escrow change its own code or deploy new contracts — entry 26's
/// "defended by absence" claim depends on none of them being reachable.
pub const DENY_LIST: &[DeniedFunction] = &[
    DeniedFunction {
        name: "update_current_contract_wasm",
        reason: "upgrades the running contract's code, i.e. an upgrade key by another name",
    },
    DeniedFunction {
        name: "update_current_contract_executable_ref",
        reason: "points the running contract at different executable code",
    },
    DeniedFunction {
        name: "upload_wasm",
        reason: "installs new contract code into the ledger",
    },
    DeniedFunction {
        name: "create_contract",
        reason: "deploys a contract from this one (a deployer capability)",
    },
    DeniedFunction {
        name: "create_contract_with_constructor",
        reason: "deploys a contract from this one (a deployer capability)",
    },
    DeniedFunction {
        name: "create_asset_contract",
        reason: "deploys or wraps an asset contract from this one",
    },
    DeniedFunction {
        name: "create_external_ref_contract",
        reason: "deploys an external-reference contract from this one",
    },
];

/// Everything a scan found.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Scan {
    /// Every WASM `(module, field)` import.
    pub imports: ImportList,
    /// `module:field` -> resolved host function name, sorted by import.
    pub resolved: BTreeMap<String, Option<String>>,
    /// Resolved host functions that are on [`DENY_LIST`].
    pub denied: Vec<&'static DeniedFunction>,
}

impl Scan {
    /// Imports whose short name could not be resolved against `env.json`.
    pub fn unmapped(&self) -> impl Iterator<Item = (&String, &Option<String>)> {
        self.resolved.iter().filter(|(_, name)| name.is_none())
    }

    /// A stable, human-readable one-line-per-import rendering.
    ///
    /// Lines are sorted, so a diff is exactly "this capability was added or
    /// removed" rather than a reordering.
    pub fn render(&self) -> String {
        let mut out = String::new();
        out.push_str("# Soroban host imports of the release WASM.\n");
        out.push_str("# Generated by tools/wasm-imports; regenerate with `--update`.\n");
        out.push_str("# module:import  host function\n");
        for (import, function) in &self.resolved {
            let name = function.as_deref().unwrap_or("<unmapped>");
            writeln!(out, "{import}  {name}").expect("writing to a String cannot fail");
        }
        out
    }
}

/// Parses the embedded `env.json` into `module -> prefix` and
/// `prefix + suffix -> function name`.
fn host_function_table() -> BTreeMap<String, String> {
    let root: serde_json::Value =
        serde_json::from_str(ENV_JSON).expect("vendored env.json must be valid JSON");
    let modules = root["modules"]
        .as_array()
        .expect("env.json must have a `modules` array");

    let mut table = BTreeMap::new();
    for module in modules {
        let prefix = module["export"]
            .as_str()
            .expect("every env.json module must carry an export prefix");
        let functions = module["functions"]
            .as_array()
            .expect("every env.json module must have a `functions` array");
        for function in functions {
            let suffix = function["export"]
                .as_str()
                .expect("every env.json function must carry an export suffix");
            let name = function["name"]
                .as_str()
                .expect("every env.json function must have a name");
            table.insert(format!("{prefix}{suffix}"), name.to_string());
        }
    }
    table
}

/// Maps a WASM `(module, field)` import to its Soroban host function name.
///
/// `None` means the import is not a Soroban host call this build understands
/// (an unknown module, or a field that a newer/older SDK does not list). That
/// is deliberately not an error: the snapshot still records the raw import,
/// so an unrecognised name is visible in review instead of being dropped.
pub fn resolve_host_function(module: &str, field: &str) -> Option<String> {
    let host = host_function_table();
    // The guest's `link(wasm_import_module = ...)` is the module's *export
    // prefix*, and the import field is the function's export suffix — so
    // `("ledger" module prefix "l", field "_")` is the short name `l_`.
    // Accept a pre-joined field too, for tools that emit `env` + `l6`.
    host.get(&format!("{module}{field}"))
        .or_else(|| host.get(field))
        .or_else(|| host.get(&format!("{module}:{field}")))
        .cloned()
}

/// Reads the WASM at `path` and returns every import it declares.
pub fn scan_wasm(path: &Path) -> Result<Scan, String> {
    let bytes =
        std::fs::read(path).map_err(|e| format!("cannot read WASM at {}: {e}", path.display()))?;
    scan_bytes(&bytes)
}

/// Same as [`scan_wasm`], for bytes already in memory (used by tests and by
/// callers that embed a fixture).
pub fn scan_bytes(bytes: &[u8]) -> Result<Scan, String> {
    let imports = raw_imports(bytes)?;

    let mut resolved = BTreeMap::new();
    for (module, field) in &imports {
        let qualified = format!("{module}:{field}");
        // Two module prefixes cannot normally produce the same qualified
        // name; keep the first if they somehow do rather than silently
        // dropping the import from the snapshot.
        resolved
            .entry(qualified)
            .or_insert_with(|| resolve_host_function(module, field));
    }

    let mut denied: Vec<&'static DeniedFunction> = Vec::new();
    for function in resolved.values().flatten() {
        if let Some(entry) = DENY_LIST.iter().find(|entry| entry.name == function) {
            denied.push(entry);
        }
    }
    denied.sort_by(|a, b| a.name.cmp(b.name));
    denied.dedup_by(|a, b| a.name == b.name);

    Ok(Scan {
        imports,
        resolved,
        denied,
    })
}

/// Reads the committed snapshot, if it exists.
pub fn read_snapshot(path: &Path) -> Result<Option<String>, String> {
    match std::fs::read_to_string(path) {
        Ok(text) => Ok(Some(text)),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(format!("cannot read snapshot at {}: {e}", path.display())),
    }
}

/// Writes `rendered` to `path`, creating parent directories.
pub fn write_snapshot(path: &Path, rendered: &str) -> Result<(), String> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|e| format!("cannot create {}: {e}", parent.display()))?;
    }
    std::fs::write(path, rendered).map_err(|e| format!("cannot write {}: {e}", path.display()))
}

/// Fail if `scan` imports anything on [`DENY_LIST`].
pub fn check_denied(scan: &Scan) -> Result<(), String> {
    if scan.denied.is_empty() {
        return Ok(());
    }
    let mut message = String::from("denylisted host function(s) linked into the WASM:\n");
    for entry in &scan.denied {
        writeln!(message, "  - {}: {}", entry.name, entry.reason)
            .expect("writing to a String cannot fail");
    }
    message.push_str(
        "\nThis contract is defended by the absence of upgrade/deploy capabilities; \
         see docs/threat-model.md entry 26.\n",
    );
    Err(message)
}

/// Fail if `scan` differs from the committed snapshot.
///
/// When the snapshot does not exist yet, this is an error that points at
/// `--update` rather than a silent pass: a guard that has never been armed is
/// worse than a loud missing file.
pub fn check_snapshot(scan: &Scan, path: &Path) -> Result<(), String> {
    let rendered = scan.render();
    match read_snapshot(path)? {
        Some(committed) if committed == rendered => Ok(()),
        Some(committed) => Err(format!(
            "the WASM's host imports differ from the committed snapshot at {}.\n\
             If the new capability is intentional, review it and run:\n\
             \n    cargo run --manifest-path tools/wasm-imports/Cargo.toml -- --update\n\
             \nExpected:\n{}\nActual:\n{}",
            path.display(),
            committed,
            rendered
        )),
        None => Err(format!(
            "no import snapshot at {} — generate it with:\n\
             \n    cargo run --manifest-path tools/wasm-imports/Cargo.toml -- --update\n",
            path.display()
        )),
    }
}

/// Default release-WASM path used when `--wasm` is not given.
///
/// This is what `stellar contract build` produces for the escrow contract
/// (`contracts/escrow/Cargo.toml` names the package `harvestlock-escrow`).
pub const DEFAULT_WASM: &str = "target/wasm32v1-none/release/harvestlock_escrow.wasm";

/// Default committed snapshot path used when `--snapshot` is not given.
pub const DEFAULT_SNAPSHOT: &str = "tools/wasm-imports/imports.snapshot";

/// CLI entry point. Returns a process exit code.
///
/// Usage:
/// `wasm-imports [--wasm PATH] [--snapshot PATH] [--update] [--print-only]`
pub fn run<I: IntoIterator<Item = String>>(args: I) -> i32 {
    let mut wasm = PathBuf::from(DEFAULT_WASM);
    let mut snapshot = PathBuf::from(DEFAULT_SNAPSHOT);
    let mut update = false;
    let mut print_only = false;

    let mut args = args.into_iter();
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--wasm" => match args.next() {
                Some(value) => wasm = PathBuf::from(value),
                None => return usage("--wasm needs a path"),
            },
            "--snapshot" => match args.next() {
                Some(value) => snapshot = PathBuf::from(value),
                None => return usage("--snapshot needs a path"),
            },
            "--update" => update = true,
            "--print-only" => print_only = true,
            "-h" | "--help" => {
                println!("{}", USAGE);
                return 0;
            }
            other => return usage(&format!("unknown argument: {other}")),
        }
    }

    let scan = match scan_wasm(&wasm) {
        Ok(scan) => scan,
        Err(e) => {
            eprintln!("error: {e}");
            eprintln!(
                "\nBuild the release WASM first (from the repository root):\n\
                 \n    stellar contract build\n"
            );
            return 2;
        }
    };

    print!("{}", scan.render());
    if scan.imports.is_empty() {
        eprintln!("note: the WASM declares no imports at all — is it a real Soroban contract?");
    }
    for (import, _) in scan.unmapped() {
        eprintln!("warning: {import} is not in the vendored env.json (new SDK?)");
    }

    if update {
        if let Err(e) = write_snapshot(&snapshot, &scan.render()) {
            eprintln!("error: {e}");
            return 2;
        }
        println!("\nwrote snapshot to {}", snapshot.display());
        return 0;
    }

    if print_only {
        return 0;
    }

    if let Err(e) = check_denied(&scan).and_then(|()| check_snapshot(&scan, &snapshot)) {
        eprintln!("\nerror: {e}");
        return 1;
    }

    println!(
        "\nok: no denylisted host imports; snapshot matches {}",
        snapshot.display()
    );
    0
}

fn usage(message: &str) -> i32 {
    eprintln!("error: {message}\n\n{USAGE}");
    2
}

const USAGE: &str = "\
wasm-imports — list a Soroban contract WASM's host imports and guard the denylist.

Usage:
    wasm-imports [--wasm PATH] [--snapshot PATH] [--update] [--print-only]

Options:
    --wasm PATH       Release WASM to scan (default: target/wasm32v1-none/release/harvestlock_escrow.wasm)
    --snapshot PATH   Committed import snapshot (default: tools/wasm-imports/imports.snapshot)
    --update          Rewrite the snapshot from the current WASM, then exit 0
    --print-only      Print the import list without checking denylist or snapshot
    -h, --help        Show this help

Without flags the tool prints every import, fails on a denylisted host
function, and fails if the committed snapshot has drifted.";

/// Convenience for tests and doc examples: resolve the short name a module
/// and field pair compiles to.
pub fn short_name(module: &str, field: &str) -> String {
    format!("{module}:{field}")
}

/// Parses every import in `bytes` and returns the raw pairs, including
/// duplicates across the same module (used to pin the regression that a
/// module-keyed map dropped all but one import per module).
pub fn raw_imports(bytes: &[u8]) -> Result<ImportList, String> {
    let mut imports = ImportList::new();
    for payload in Parser::new(0).parse_all(bytes) {
        let payload = payload.map_err(|e| format!("malformed WASM: {e}"))?;
        if let Payload::ImportSection(section) = payload {
            for import in section.into_imports() {
                let import = import.map_err(|e| format!("malformed import section: {e}"))?;
                imports.insert((import.module.to_string(), import.name.to_string()));
            }
        }
    }
    Ok(imports)
}

/// The set of resolved host function names, for tests that only care about
/// the capability list.
pub fn host_functions(scan: &Scan) -> BTreeSet<String> {
    scan.resolved.values().flatten().cloned().collect()
}

/// Every host function name the vendored `env.json` knows about.
pub fn known_host_functions() -> BTreeSet<String> {
    host_function_table().into_values().collect()
}
